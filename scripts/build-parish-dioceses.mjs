// Writes parish/dioceses.js -- the diocese dropdown for the parish registration form -- from the
// site's own TEC_DIOCESE_DIRECTORY in js/cycles-of-prayer.js, so the two never drift apart in
// spelling. (That file is large and has other side effects, so the parish pages get this small
// generated copy instead of loading it.) Re-run after the directory changes:
//   node scripts/build-parish-dioceses.mjs
import fs from "node:fs";

const src = fs.readFileSync("js/cycles-of-prayer.js", "utf8");
const bodyMatch = src.match(/const TEC_DIOCESE_DIRECTORY_BODY_SLUG = '([a-z0-9-]+)'/);
const blockMatch = src.match(/const TEC_DIOCESE_DIRECTORY = Object\.freeze\(\[([\s\S]*?)\n\]\);/);
if (!bodyMatch || !blockMatch) { console.error("FAIL: could not find TEC_DIOCESE_DIRECTORY in js/cycles-of-prayer.js"); process.exit(1); }

const entries = [...blockMatch[1].matchAll(/\{\s*dioceseShort:\s*'([a-z0-9-]+)',\s*label:\s*'([^']+)'\s*\}/g)]
  .map((m) => ({ key: `${bodyMatch[1]}/${m[1]}`, label: m[2] }));
if (entries.length < 100) { console.error(`FAIL: only ${entries.length} dioceses parsed`); process.exit(1); }

const body = `/* GENERATED by scripts/build-parish-dioceses.mjs from TEC_DIOCESE_DIRECTORY in js/cycles-of-prayer.js.
 * Do not edit by hand. Each key has the form "episcopal/<dioceseShort>", the same shape the site's
 * profile stores and the API validates (^[a-z0-9-]{1,40}/[a-z0-9-]{1,80}$). */
window.UO_DIOCESES = Object.freeze([
${entries.map((e) => `  { key: ${JSON.stringify(e.key)}, label: ${JSON.stringify(e.label)} }`).join(",\n")}
]);
`;
fs.writeFileSync("parish/dioceses.js", body);
console.log(`wrote parish/dioceses.js (${entries.length} dioceses)`);
